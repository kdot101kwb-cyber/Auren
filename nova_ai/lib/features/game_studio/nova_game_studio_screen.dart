import 'package:cross_file/cross_file.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';
import 'package:url_launcher/url_launcher.dart';

import 'nova_game_pipeline.dart';
import 'nova_game_tool_catalog.dart';

/// Creates a deterministic Godot starter and exposes a staged tool workflow.
/// Actual engine execution requires a compatible, configured build runner.
class NovaGameStudioScreen extends StatefulWidget {
  const NovaGameStudioScreen({super.key});

  @override
  State<NovaGameStudioScreen> createState() => _NovaGameStudioScreenState();
}

class _NovaGameStudioScreenState extends State<NovaGameStudioScreen> {
  final idea = TextEditingController();
  final search = TextEditingController();
  String query = '';
  String? projectFile;
  String? sceneFile;
  String? scriptFile;
  String projectName = 'NOVA Starter Game';
  bool exporting = false;

  @override
  void dispose() {
    idea.dispose();
    search.dispose();
    super.dispose();
  }

  void generate() {
    final concept = idea.text.trim();
    if (concept.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('اكتب فكرة اللعبة أولاً.')),
      );
      return;
    }
    final rawName = concept.split(RegExp(r'[,،.!?\n]')).first.trim();
    final name = rawName.replaceAll(RegExp(r'[^a-zA-Z0-9 _-]'), '');
    setState(() {
      projectName = name.isEmpty ? 'NOVA Starter Game' : name;
      sceneFile = '''[gd_scene load_steps=2 format=3]

[ext_resource type="Script" path="res://main.gd" id="1_script"]

[node name="Main" type="Node2D"]
script = ExtResource("1_script")
''';
      projectFile = '''; Generated by NOVA Game Studio - Godot 4
config_version=5

[application]
config/name="$projectName"
run/main_scene="res://main.tscn"

[rendering]
renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
''';
      scriptFile = '''extends Node2D

# User game idea: $concept
# Starter gameplay: move with arrow keys, collect the gold orb, gain a point.
var player := Vector2(240, 300)
var coin := Vector2(100, 120)
var score := 0
var collected := false

func _process(delta: float) -> void:
    player += Input.get_vector("ui_left", "ui_right", "ui_up", "ui_down") * 260.0 * delta
    var bounds := get_viewport_rect().size
    player.x = clampf(player.x, 18.0, bounds.x - 18.0)
    player.y = clampf(player.y, 18.0, bounds.y - 18.0)
    if not collected and player.distance_to(coin) < 28.0:
        collected = true
        score += 1
    queue_redraw()

func _draw() -> void:
    draw_rect(Rect2(Vector2.ZERO, get_viewport_rect().size), Color("#111827"))
    if not collected:
        draw_circle(coin, 13.0, Color("#fbbf24"))
    draw_circle(player, 18.0, Color("#60a5fa"))
    draw_string(ThemeDB.fallback_font, Vector2(18, 30),
        "Score: %d | Move with arrow keys" % score, HORIZONTAL_ALIGNMENT_LEFT, -1, 18, Color.WHITE)
''';
    });
  }

  Future<void> copyFile(String? content, String filename) async {
    if (content == null) return;
    await Clipboard.setData(ClipboardData(text: content));
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('تم نسخ $filename')),
      );
    }
  }

  Future<void> exportProject() async {
    if (projectFile == null || sceneFile == null || scriptFile == null || exporting) {
      return;
    }
    setState(() => exporting = true);
    try {
      final archive = Archive();
      void addTextFile(String name, String content) {
        final bytes = Uint8List.fromList(utf8.encode(content));
        archive.addFile(ArchiveFile(name, bytes.length, bytes));
      }

      addTextFile('project.godot', projectFile!);
      addTextFile('main.tscn', sceneFile!);
      addTextFile('main.gd', scriptFile!);
      addTextFile(
        'README.txt',
        'Generated by NOVA Game Studio.\n'
        'Open this project with Godot 4 on a compatible computer to run and extend it.\n'
        'NOVA has not run or playtested this project. This ZIP is source code, not an APK.\n'
        'Idea: ${idea.text.trim()}\n',
      );
      final zipBytes = ZipEncoder().encode(archive);
      if (zipBytes.isEmpty) throw StateError('The project ZIP is empty.');
      final directory = await getTemporaryDirectory();
      final safeName = projectName
          .replaceAll(RegExp(r'[^a-zA-Z0-9_-]+'), '_')
          .replaceAll(RegExp(r'^_+|_+$'), '');
      final file = File(
        '${directory.path}/${safeName.isEmpty ? 'nova_game' : safeName}.zip',
      );
      await file.writeAsBytes(zipBytes, flush: true);
      if (!mounted) return;
      await SharePlus.instance.share(
        ShareParams(
          files: [XFile(file.path, mimeType: 'application/zip')],
          text: 'NOVA Game Studio — Godot 4 starter project source',
        ),
      );
    } catch (error) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('تعذر تصدير المشروع: $error')),
        );
      }
    } finally {
      if (mounted) setState(() => exporting = false);
    }
  }

  Future<void> openRepo(String url) async {
    final uri = Uri.tryParse(url);
    if (uri != null) await launchUrl(uri, mode: LaunchMode.externalApplication);
  }

  @override
  Widget build(BuildContext context) {
    final tools = NovaGameToolCatalog.search(query);
    return Scaffold(
      appBar: AppBar(title: const Text('NOVA Game Studio')),
      body: ListView(
        padding: const EdgeInsets.all(16),
        children: [
          Card(
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text('حوّل الفكرة إلى بداية لعبة',
                      style: Theme.of(context).textTheme.titleLarge),
                  const SizedBox(height: 8),
                  const Text(
                    'ينشئ NOVA نموذج Godot 4 أولياً ويجمع أدوات بناء الألعاب في مسار عمل واحد. الأدوات ليست مثبتة أو متصلة تلقائياً.',
                  ),
                  const SizedBox(height: 12),
                  TextField(
                    key: const Key('game_idea_input'),
                    controller: idea,
                    minLines: 2,
                    maxLines: 4,
                    decoration: const InputDecoration(
                      border: OutlineInputBorder(),
                      labelText: 'فكرة اللعبة',
                    ),
                  ),
                  const SizedBox(height: 12),
                  SizedBox(
                    width: double.infinity,
                    child: FilledButton.icon(
                      key: const Key('generate_game_button'),
                      onPressed: generate,
                      icon: const Icon(Icons.auto_awesome),
                      label: const Text('أنشئ ملفات اللعبة'),
                    ),
                  ),
                  if (scriptFile != null) ...[
                    const Divider(height: 28),
                    Text(projectName,
                        style: Theme.of(context).textTheme.titleMedium),
                    const Text(
                      'النموذج الحالي لعبة 2D أولية. لم يتم تشغيل Godot أو اختبار اللعب أو تصدير APK.',
                    ),
                    SizedBox(
                      width: double.infinity,
                      child: FilledButton.icon(
                        key: const Key('export_game_zip_button'),
                        onPressed: exporting ? null : exportProject,
                        icon: exporting
                            ? const SizedBox(
                                width: 18,
                                height: 18,
                                child: CircularProgressIndicator(strokeWidth: 2),
                              )
                            : const Icon(Icons.archive_outlined),
                        label: Text(exporting
                            ? 'جارٍ تجهيز المشروع...'
                            : 'صدّر ملفات المشروع ZIP'),
                      ),
                    ),
                    ExpansionTile(
                      title: const Text('project.godot'),
                      children: [
                        TextButton.icon(
                          onPressed: () => copyFile(projectFile, 'project.godot'),
                          icon: const Icon(Icons.copy),
                          label: const Text('نسخ الملف'),
                        ),
                        Padding(
                          padding: const EdgeInsets.all(12),
                          child: SelectableText(projectFile!),
                        ),
                      ],
                    ),
                    ExpansionTile(
                      title: const Text('main.tscn'),
                      children: [
                        TextButton.icon(
                          onPressed: () => copyFile(sceneFile, 'main.tscn'),
                          icon: const Icon(Icons.copy),
                          label: const Text('نسخ الملف'),
                        ),
                        Padding(
                          padding: const EdgeInsets.all(12),
                          child: SelectableText(sceneFile!),
                        ),
                      ],
                    ),
                    ExpansionTile(
                      title: const Text('main.gd'),
                      children: [
                        TextButton.icon(
                          onPressed: () => copyFile(scriptFile, 'main.gd'),
                          icon: const Icon(Icons.copy),
                          label: const Text('نسخ الملف'),
                        ),
                        Padding(
                          padding: const EdgeInsets.all(12),
                          child: SelectableText(scriptFile!),
                        ),
                      ],
                    ),
                  ],
                ],
              ),
            ),
          ),
          const SizedBox(height: 16),
          Text('مسار صناعة اللعبة',
              style: Theme.of(context).textTheme.titleLarge),
          const SizedBox(height: 6),
          const Text(
            'المراحل توضح كيف ستتعاون الأدوات. المراحل التي تحتاج محركاً أو MCP لا تُعتبر منفذة حتى يتصل مشغّل بناء فعلي وتنجح الاختبارات.',
          ),
          for (final stage in NovaGamePipeline.stages)
            Card(
              child: ExpansionTile(
                leading: Icon(
                  stage.status == NovaGameStageStatus.readyToGenerate
                      ? Icons.check_circle_outline
                      : stage.status == NovaGameStageStatus.needsRunner
                          ? Icons.computer
                          : Icons.extension_outlined,
                ),
                title: Text(stage.title),
                subtitle: Text(stage.description),
                children: [
                  Padding(
                    padding: const EdgeInsets.fromLTRB(16, 0, 16, 12),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text('شرط الإنجاز: ${stage.completionGate}'),
                        const SizedBox(height: 8),
                        for (final tool in stage.tools)
                          ListTile(
                            dense: true,
                            contentPadding: EdgeInsets.zero,
                            title: Text(tool.name),
                            subtitle: Text(tool.integrationStatus),
                            trailing: IconButton(
                              tooltip: 'فتح GitHub',
                              icon: const Icon(Icons.open_in_new),
                              onPressed: () => openRepo(tool.repository),
                            ),
                          ),
                      ],
                    ),
                  ),
                ],
              ),
            ),
          const SizedBox(height: 12),
          Text('كتالوج الأدوات المجانية (${tools.length})',
              style: Theme.of(context).textTheme.titleLarge),
          const SizedBox(height: 8),
          TextField(
            key: const Key('game_tools_search'),
            controller: search,
            onChanged: (value) => setState(() => query = value),
            decoration: const InputDecoration(
              border: OutlineInputBorder(),
              prefixIcon: Icon(Icons.search),
              labelText: 'ابحث عن أداة',
            ),
          ),
          const SizedBox(height: 8),
          for (final tool in tools)
            Card(
              child: ListTile(
                title: Text(tool.name),
                subtitle: Text('${tool.purpose}\nالحالة: ${tool.integrationStatus}'),
                isThreeLine: true,
                trailing: IconButton(
                  icon: const Icon(Icons.open_in_new),
                  tooltip: 'فتح GitHub',
                  onPressed: () => openRepo(tool.repository),
                ),
              ),
            ),
        ],
      ),
    );
  }
}
